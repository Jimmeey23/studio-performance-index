for (const s of r.sections) console.log(s.id, 'kpis', s.kpis.length, 'charts', s.charts.map((c) => c.result.rows.length), 'tables', s.tables.map((x) => x.result.rows.length), 'visuals', Object.keys(s.visuals ?? {}).join(','));
